test('every Live Brain UI and status key has ru, zh, ja, and es translations', () => {
    const dicts = { ru: LIVE_BRAIN_RU, zh: LIVE_BRAIN_ZH, ja: LIVE_BRAIN_JA, es: LIVE_BRAIN_ES };
    for (const [lang, dict] of Object.entries(dicts)) {
        const missing = REQUIRED_LIVE_BRAIN_KEYS.filter((key) => typeof dict[key] !== 'string' || dict[key].length === 0);
        assert.deepEqual(missing, [], `${lang} is missing Live Brain translations`);
    }
    const settingsSrc = readFileSync(new URL('../SettingsOverlay.tsx', import.meta.url), 'utf8');
    assert.ok(settingsSrc.includes('liveBrainPrivacyNotice('), 'SettingsOverlay should render D5 privacy notice');
});
